from __future__ import annotations
import json
from datetime import datetime
from pathlib import Path
from mcp_assistant.eval.metrics import EvalReport


def generate_report(report: EvalReport, output_dir: Path) -> tuple[Path, Path]:
    """Write JSON + Markdown report. Returns (json_path, md_path)."""
    output_dir.mkdir(parents=True, exist_ok=True)
    ts = datetime.now().strftime("%Y%m%d_%H%M%S")
    label = report.ablation_label.replace(" ", "_")

    json_path = output_dir / f"results_{label}_{ts}.json"
    md_path = output_dir / f"report_{label}_{ts}.md"

    json_path.write_text(json.dumps(report.to_dict(), indent=2), encoding="utf-8")
    md_path.write_text(_render_markdown(report), encoding="utf-8")

    return json_path, md_path


def _render_markdown(report: EvalReport) -> str:
    s = report
    lines: list[str] = []

    lines += [
        f"# MCP Terminal Assistant — Evaluation Report",
        f"",
        f"**Date:** {datetime.now().strftime('%Y-%m-%d %H:%M')}  ",
        f"**Model:** {s.model}  ",
        f"**Ablation:** {s.ablation_label}  ",
        f"**Context window:** {s.context_window} turns  ",
        f"**Confidence threshold:** {s.confidence_threshold}  ",
        f"",
        f"---",
        f"",
        f"## Summary Metrics",
        f"",
        f"| Metric | Value | Target |",
        f"|--------|-------|--------|",
        f"| Tool Accuracy        | {s.tool_accuracy():.1%}   | > 85%  |",
        f"| Action Accuracy      | {s.action_accuracy():.1%}   | > 75%  |",
        f"| Parse Failure Rate   | {s.parse_failure_rate():.1%}   | < 10%  |",
        f"| Hallucination Rate   | {s.hallucination_rate():.1%}   | < 5%   |",
        f"| Faithfulness Score   | {s.faithfulness_score():.1%}   | > 75%  |",
        f"| Mean Latency         | {s.mean_latency_ms():.0f} ms  | < 3000 ms |",
        f"| P95 Latency          | {s.p95_latency_ms():.0f} ms  | < 6000 ms |",
        f"| Total Evaluated      | {len(s.results)}    | {len(s.results)}     |",
        f"",
        f"---",
        f"",
        f"## Per-Category Breakdown",
        f"",
        f"| Category | Count | Tool Acc | Action Acc | Mean Latency |",
        f"|----------|-------|----------|------------|--------------|",
    ]

    for cat, m in sorted(s.per_category().items()):
        lines.append(
            f"| {cat:<12} | {m['count']:>5} | {m['tool_accuracy']:.1%}    | "
            f"{m['action_accuracy']:.1%}      | {m['mean_latency_ms']:.0f} ms        |"
        )

    lines += [
        f"",
        f"---",
        f"",
        f"## Per-Difficulty Breakdown",
        f"",
        f"| Difficulty | Count | Tool Acc | Action Acc |",
        f"|------------|-------|----------|------------|",
    ]

    for diff in ["easy", "medium", "hard"]:
        m = s.per_difficulty().get(diff, {})
        if m:
            lines.append(
                f"| {diff:<10} | {m['count']:>5} | {m['tool_accuracy']:.1%}    | "
                f"{m['action_accuracy']:.1%}      |"
            )

    lines += [
        "",
        "---",
        "",
        "## Per-Model Breakdown",
        "",
        "| Model | Count | Tool Acc | Action Acc |",
        "|-------|-------|----------|------------|",
    ]

    for model, m in sorted(s.per_model().items()):
        lines.append(
            f"| {model} | {m['count']:>5} | {m['tool_accuracy']:.1%} | {m['action_accuracy']:.1%} |"
        )

    # Latency ASCII histogram
    lines += ["", "---", "", "## Latency Distribution", ""]
    lines += _ascii_histogram([r.latency_ms for r in s.results])

    # Failures section
    failures = s.failures()
    if failures:
        lines += [
            "",
            "---",
            "",
            f"## Failed Cases ({len(failures)} / {len(s.results)})",
            "",
        ]
        for r in failures[:20]:   # cap at 20 to keep report readable
            status = "PARSE_ERR" if r.parse_failed else "WRONG"
            lines += [
                f"### [{status}] ID {r.item_id} — {r.category} / {r.difficulty}",
                f"**Input:** {r.nl_input}  ",
                f"**Expected:** `{r.gt_tool}.{r.gt_action}`  ",
                f"**Got:** `{r.pred_tool}.{r.pred_action}` (conf {r.pred_confidence:.2f})  ",
                f"**Latency:** {r.latency_ms:.0f} ms  ",
                f"",
            ]
        if len(failures) > 20:
            lines.append(f"_... and {len(failures) - 20} more (see JSON for full list)_")

    lines += ["", "---", "", "_Generated by MCP Terminal Assistant eval harness_"]
    return "\n".join(lines)


def _ascii_histogram(values: list[float], bins: int = 8, width: int = 30) -> list[str]:
    if not values:
        return ["_(no data)_"]
    lo, hi = min(values), max(values)
    if lo == hi:
        return [f"All values: {lo:.0f} ms"]
    step = (hi - lo) / bins
    counts = [0] * bins
    for v in values:
        idx = min(int((v - lo) / step), bins - 1)
        counts[idx] += 1
    max_c = max(counts) or 1
    lines = ["```"]
    for i, c in enumerate(counts):
        lo_b = lo + i * step
        hi_b = lo_b + step
        bar = "█" * int(c / max_c * width)
        lines.append(f"{lo_b:>6.0f}-{hi_b:<6.0f} ms | {bar:<{width}} {c}")
    lines.append("```")
    return lines
